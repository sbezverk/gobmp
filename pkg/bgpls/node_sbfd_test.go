package bgpls

import (
	"reflect"
	"testing"
)

func TestGetNodeSBFDDiscriminators(t *testing.T) {
	// RFC 9247 §3: TLV 1032 (0x0408) contains one or more four-octet values.
	tests := []struct {
		name string
		wire []byte
		want []uint32
	}{
		{
			name: "no valid discriminators",
			wire: []byte{
				0x04, 0x01, 0x00, 0x04, 0x11, 0x22, 0x33, 0x44, // Unrelated TLV with a four-octet value.
				0x04, 0x08, 0x00, 0x00,
				0x04, 0x08, 0x00, 0x03, 0x11, 0x22, 0x33,
				0x04, 0x08, 0x00, 0x05, 0x11, 0x22, 0x33, 0x44, 0xff,
			},
		},
		{
			name: "wire order and duplicates preserved",
			wire: []byte{
				0x04, 0x08, 0x00, 0x08, 0xff, 0xff, 0xff, 0xff, 0x01, 0x02, 0x03, 0x04,
				0x04, 0x01, 0x00, 0x04, 0x11, 0x22, 0x33, 0x44,
				0x04, 0x08, 0x00, 0x05, 0x11, 0x22, 0x33, 0x44, 0xff,
				0x04, 0x08, 0x00, 0x04, 0xff, 0xff, 0xff, 0xff,
			},
			want: []uint32{0xffffffff, 0x01020304, 0xffffffff},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			nlri, err := UnmarshalBGPLSNLRI(tt.wire)
			if err != nil {
				t.Fatalf("UnmarshalBGPLSNLRI() error: %v", err)
			}
			if got := nlri.GetNodeSBFDDiscriminators(); !reflect.DeepEqual(got, tt.want) {
				t.Errorf("GetNodeSBFDDiscriminators() = %#v, want %#v", got, tt.want)
			}
		})
	}
}
